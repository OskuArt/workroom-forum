'    const maxId=String(maxRow.max_id||"0");',
'    const after=String(req.query.after||"");',
'    if(!/^\\d+$/.test(after))return res.json({cursor:maxId,events:[]});',
'    const rows=(await pool.query("SELECT msg.id,msg.match_id,msg.kind,msg.body,msg.image_data,msg.created_at,m.mode,u.id AS sender_id,u.profile AS sender_profile FROM messages msg JOIN matches m ON m.id=msg.match_id JOIN users u ON u.id=msg.sender_id LEFT JOIN chat_preferences cp ON cp.user_id=$1 AND cp.match_id=m.id WHERE msg.id>$2::bigint AND msg.sender_id IS NOT NULL AND msg.sender_id<>$1 AND (m.user1=$1 OR m.user2=$1) AND COALESCE(cp.muted,FALSE)=FALSE ORDER BY msg.id ASC LIMIT 50",[req.user.id,after])).rows;',
