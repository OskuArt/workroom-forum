'    if(!V7_REACTIONS.has(emoji))return res.status(400).json({error:"bad_reaction"});',
'    const existing=(await pool.query("SELECT emoji FROM message_reactions WHERE message_id=$1 AND user_id=$2",[messageId,req.user.id])).rows[0];',
'    if(existing&&existing.emoji===emoji){',
'      await pool.query("DELETE FROM message_reactions WHERE message_id=$1 AND user_id=$2",[messageId,req.user.id]);',
'      return res.json({ok:true,removed:true});',
'    }',
'    await pool.query("INSERT INTO message_reactions(message_id,user_id,emoji) VALUES($1,$2,$3) ON CONFLICT(message_id,user_id) DO UPDATE SET emoji=EXCLUDED.emoji,created_at=NOW()",[messageId,req.user.id,emoji]);',
'    res.json({ok:true,emoji});',
'  }catch(e){next(e)}',
'});',
'',
'app.get("/api/chat-events-v7", requireUser, async(req,res,next)=>{',
'  try{',
