'  }catch(e){next(e)}',
'});',
'',
'app.patch("/api/dates/:id/outcome-v7", requireUser, async(req,res,next)=>{',
'  try{',
'    const status=String(req.body.status||"");',
'    if(!["completed","cancelled"].includes(status))return res.status(400).json({error:"bad_status"});',
'    const d=(await pool.query("SELECT d.*,m.user1,m.user2 FROM dates d JOIN matches m ON m.id=d.match_id WHERE d.id=$1 AND (m.user1=$2 OR m.user2=$2)",[req.params.id,req.user.id])).rows[0];',
'    if(!d)return res.status(404).json({error:"date_not_found"});',
'    await pool.query("UPDATE dates SET status=$2,updated_at=NOW() WHERE id=$1",[d.id,status]);',
'    const other=d.user1===req.user.id?d.user2:d.user1;',
'    await pool.query("INSERT INTO notifications(user_id,type,payload) VALUES($1,\'meeting_outcome\',$2)",[other,JSON.stringify({dateId:d.id,status,mode:d.mode,from:req.user.id})]);',
'    res.json({ok:true,status});',
'  }catch(e){next(e)}',
'});',
'',
'app.patch("/api/dates/:id/edit-v7", requireUser, async(req,res,next)=>{',
'  try{',
'    const d=(await pool.query("SELECT d.*,m.user1,m.user2 FROM dates d JOIN matches m ON m.id=d.match_id WHERE d.id=$1 AND (m.user1=$2 OR m.user2=$2)",[req.params.id,req.user.id])).rows[0];',
'    if(!d)return res.status(404).json({error:"date_not_found"});',
'    const when=new Date(req.body.when);',
'    const place=String(req.body.place||"").trim();',
'    if(!Number.isFinite(+when)||!place)return res.status(400).json({error:"bad_edit"});',
'    const keepOutcome=d.status==="completed"||d.status==="cancelled";',
'    const nextStatus=keepOutcome?d.status:"pending";',
'    await pool.query("UPDATE dates SET when_at=$2,place=$3,status=$4,reminder_sent=\'{}\'::jsonb,updated_at=NOW() WHERE id=$1",[d.id,when.toISOString(),place,nextStatus]);',
'    const other=d.user1===req.user.id?d.user2:d.user1;',
'    await pool.query("INSERT INTO notifications(user_id,type,payload) VALUES($1,\'meeting_edit\',$2)",[other,JSON.stringify({dateId:d.id,status:nextStatus,mode:d.mode,from:req.user.id})]);',
'    res.json({ok:true,status:nextStatus});',
'  }catch(e){next(e)}',
'});',
'',
'app.post("/api/achievements/check-v7", requireUser, async(req,res,next)=>{',
'  try{',
'    const matches=(await pool.query("SELECT COUNT(*)::int AS c FROM matches WHERE user1=$1 OR user2=$1",[req.user.id])).rows[0].c;',
'    const dates=(await pool.query("SELECT COUNT(*)::int AS total,COUNT(*) FILTER (WHERE status=\'completed\')::int AS completed,COUNT(*) FILTER (WHERE status=\'declined\')::int AS declined FROM dates d JOIN matches m ON m.id=d.match_id WHERE m.user1=$1 OR m.user2=$1",[req.user.id])).rows[0];',
'    const tests=(await pool.query("SELECT COUNT(DISTINCT type)::int AS c FROM tests WHERE user_id=$1",[req.user.id])).rows[0].c;',
'    const p=req.user.profile||{};',
'    const defs=[',
'      {key:"first_match",title:"Первая искра",icon:"✦",ok:matches>=1},',
'      {key:"first_date",title:"По ракетам!",icon:"↗",ok:dates.total>=1},',
'      {key:"first_completed",title:"Приятного полёта",icon:"◐",ok:dates.completed>=1},',
'      {key:"two_completed",title:"Вторая глава",icon:"◑",ok:dates.completed>=2},',
'      {key:"three_completed",title:"Устойчивая орбита",icon:"●",ok:dates.completed>=3},',
